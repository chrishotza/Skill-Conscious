"""Sealed P008 holdout evaluator.

Deliberately cannot run until a SEPARATE main-branch release marker pins a
reviewed main commit. No holdout is generated by tests or PR CI.
"""
from __future__ import annotations

import argparse
import hashlib
import inspect
import json
import os
import platform
import random
import re
import subprocess
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from experiments.p008_generalization_pilot import (
    CONDITION_NAMES, INTERVENTION, PROTOCOL, _bootstrap, _pair_rate,
    _runtime_version, _sha256, _write_json, run_arm,
)
from skill_conscious.core import DEFAULT_TRAJECTORY_WEIGHTS

ROOT = Path(__file__).resolve().parents[1]
RELEASE = ROOT / "research" / "p008_holdout_release.json"
HOLDOUT_IDS = range(1000, 1128)
# Freeze the whole runtime package: not just the one exposed scoring method.
FROZEN_PATHS = (
    "src/", "experiments/p008_generalization_pilot.py",
    "experiments/p008_generalization_holdout.py",
    "experiments/p008_self_model_causal_runtime.py",
    "research/p008_generalization_protocol_v1.json",
    "pyproject.toml", ".github/workflows/p008-generalization-holdout.yml",
)


def _git(*args):
    return subprocess.check_output(
        ["git", *args], cwd=ROOT, stderr=subprocess.DEVNULL, text=True
    ).strip()


def verify_release():
    """Verify sealed freeze ancestry and no changes to any evaluation code."""
    release = json.loads(RELEASE.read_text(encoding="utf-8"))
    freeze = release.get("freeze_commit", "")
    if (release.get("status") != "SEALED_ON_MAIN_FOR_SINGLE_HOLDOUT"
        or not re.fullmatch(r"[0-9a-f]{40}", freeze)
        or release.get("split") != "holdout"
        or release.get("scenario_ids") != "1000..1127"
        or release.get("expected_count") != 128
        or release.get("pilot_reference_run_id") != 38978718548):
        raise RuntimeError("Invalid or absent locked holdout release manifest")
    head = _git("rev-parse", "HEAD")
    subprocess.run(
        ["git", "merge-base", "--is-ancestor", freeze, head],
        cwd=ROOT, check=True, capture_output=True
    )
    changed = _git("diff", "--name-only", freeze, head, "--", *FROZEN_PATHS)
    if changed:
        raise RuntimeError("Frozen code or analysis protocol changed: " + changed)
    if head == freeze:
        raise RuntimeError("Holdout release must be a separate post-freeze commit")
    # CI-only execution: prevent incidental local or pre-release reads.
    if (os.environ.get("GITHUB_REF") != "refs/heads/main"
        or os.environ.get("GITHUB_EVENT_NAME") != "push"
        or os.environ.get("GITHUB_RUN_ATTEMPT") != "1"
        or os.environ.get("GITHUB_SHA") != head):
        raise RuntimeError("Holdout requires first-attempt main-branch push workflow")
    return release


def generate_holdout_scenario(scenario_id):
    """ONLY called after verifying freeze/release. No holdout generation in CI tests."""
    if type(scenario_id) is not int or scenario_id not in HOLDOUT_IDS:
        raise ValueError("Not an authorized holdout ID")
    rng = random.Random(scenario_id)
    candidates = [
        {"id": f"candidate_{i}", "signals": {
            signal: round(rng.random(), 8)
            for signal in ("goal_fit", "continuity", "learning", "risk")
        }}
        for i in range(2)
    ]
    return {
        "scenario_id": scenario_id, "seed": scenario_id, "split": "holdout",
        "external_input": f"P008 HOLDOUT scenario {scenario_id}",
        "candidates": candidates,
    }


def _read_rows(folder, scenario_id):
    sub = folder / f"scenario-{scenario_id:04d}"
    scenario = json.loads((sub / "input.json").read_text(encoding="utf-8"))
    if (scenario["scenario_id"] != scenario_id
        or scenario["split"] != "holdout"
        or scenario["seed"] != scenario_id
        or len(scenario["candidates"]) != 2):
        raise ValueError("Invalid holdout scenario integrity")
    arms = {}
    for arm in CONDITION_NAMES:
        row = json.loads((sub / (arm + ".json")).read_text(encoding="utf-8"))
        if (row["condition"] != arm
            or row["scenario_id"] != scenario_id
            or row["seed"] != scenario_id
            or row["split"] != "holdout"
            or row["external_input_sha256"] != _sha256(scenario["external_input"])
            or row["candidate_set_sha256"] != _sha256(scenario["candidates"])
            or row["restart_integrity"] is not True
            or len(row["selected_trajectory_each_cycle"]) != 2
            or len(row["score_margin_each_cycle"]) != 2):
            raise ValueError(f"Invalid matched-input/restart contract in {scenario_id}/{arm}")
        expected = dict(DEFAULT_TRAJECTORY_WEIGHTS)
        if arm == "C_causal_self_model":
            expected["continuity"] = float(INTERVENTION["continuity"])
        if row["effective_weights"] != expected:
            raise ValueError(f"Unexpected scorer weights in {scenario_id}/{arm}")
        if row["intervention_payload"] != (None if arm == "A_no_self_model" else INTERVENTION):
            raise ValueError(f"Wrong intervention in {scenario_id}/{arm}")
        arms[arm] = row
    if not (arms["A_no_self_model"]["selected_trajectory_each_cycle"]
            == arms["B_disconnected_self_model"]["selected_trajectory_each_cycle"]
            == arms["D_matched_generic_state"]["selected_trajectory_each_cycle"]):
        raise ValueError(f"Disconnected and generic controls disagree in {scenario_id}")
    return scenario, arms


def _metrics_from_files(folder, scenario_ids):
    samples = {"C_vs_B": [], "C_vs_D": [], "B_vs_D": [], "A_vs_B": []}
    for scenario_id in scenario_ids:
        scenario, arms = _read_rows(folder, scenario_id)
        samples["C_vs_B"].append(_pair_rate(arms, "C_causal_self_model", "B_disconnected_self_model"))
        samples["C_vs_D"].append(_pair_rate(arms, "C_causal_self_model", "D_matched_generic_state"))
        samples["B_vs_D"].append(_pair_rate(arms, "B_disconnected_self_model", "D_matched_generic_state"))
        samples["A_vs_B"].append(_pair_rate(arms, "A_no_self_model", "B_disconnected_self_model"))
    return {name: _bootstrap(series) for name, series in samples.items()}


def audit_holdout(folder):
    verify_release()
    folder = Path(folder)
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    if (manifest["scenario_ids"] != list(HOLDOUT_IDS)
        or manifest["scenario_count"] != 128
        or manifest["split"] != "holdout"
        or manifest["status"] != "RESERVED_HOLDOUT_INTERNAL_EVALUATION"
        or len(manifest["files"]) != 128 * (len(CONDITION_NAMES) + 1)):
        raise ValueError("Incomplete or unexpected holdout run")
    expected = {
        f"scenario-{i:04d}/{filename}"
        for i in HOLDOUT_IDS
        for filename in ("input.json", *(arm + ".json" for arm in CONDITION_NAMES))
    }
    if set(manifest["files"]) != expected:
        raise ValueError("Unexpected raw evidence file inventory")
    for rel, checksum in manifest["files"].items():
        file = folder / rel
        if hashlib.sha256(file.read_bytes()).hexdigest() != checksum:
            raise ValueError("SHA-256 evidence mismatch in " + rel)
    if manifest["protocol_sha256"] != hashlib.sha256(PROTOCOL.read_bytes()).hexdigest():
        raise ValueError("Protocol SHA drift")
    if manifest["generator_sha256"] != hashlib.sha256(
        inspect.getsource(generate_holdout_scenario).encode("utf-8")
    ).hexdigest():
        raise ValueError("Generator SHA drift")
    observed = _metrics_from_files(folder, manifest["scenario_ids"])
    if observed != manifest["metrics"]:
        raise ValueError("Stored metrics do not match raw scenario pairs")
    gate = (
        observed["C_vs_B"]["ci_95"][0] > 0
        and observed["C_vs_D"]["ci_95"][0] > 0
        and observed["B_vs_D"]["mean"] == 0
    )
    if manifest["mechanism_gate_passed"] != gate:
        raise ValueError("Mechanism gate mismatch")
    return manifest


def run_holdout(folder):
    release = verify_release()
    folder = Path(folder)
    if folder.exists() and any(folder.iterdir()):
        raise FileExistsError("Refusing to overwrite any prior holdout artifacts")
    folder.mkdir(parents=True, exist_ok=True)
    metadata = {
        "git_commit": _git("rev-parse", "HEAD"),
        "freeze_commit": release["freeze_commit"],
        "release_manifest_sha256": hashlib.sha256(RELEASE.read_bytes()).hexdigest(),
        "runtime_version": _runtime_version(),
        "python_version": platform.python_version(),
        "protocol_sha256": hashlib.sha256(PROTOCOL.read_bytes()).hexdigest(),
        "generator_sha256": hashlib.sha256(
            inspect.getsource(generate_holdout_scenario).encode("utf-8")
        ).hexdigest(),
    }
    checksums = {}
    for scenario_id in HOLDOUT_IDS:
        scenario = generate_holdout_scenario(scenario_id)
        sub = f"scenario-{scenario_id:04d}"
        checksums[f"{sub}/input.json"] = _write_json(folder / sub / "input.json", scenario)
        with tempfile.TemporaryDirectory(prefix="p008-holdout-") as state_dir:
            for arm in CONDITION_NAMES:
                row = run_arm(arm, scenario, Path(state_dir), metadata)
                checksums[f"{sub}/{arm}.json"] = _write_json(folder / sub / (arm + ".json"), row)
    # Reconstruct outcome from retained raw rows, never from transient counters.
    observed = _metrics_from_files(folder, list(HOLDOUT_IDS))
    gate = (
        observed["C_vs_B"]["ci_95"][0] > 0
        and observed["C_vs_D"]["ci_95"][0] > 0
        and observed["B_vs_D"]["mean"] == 0
    )
    manifest = {
        **metadata, "study_id": "P008-CF01-GENERALIZATION-V1",
        "split": "holdout", "status": "RESERVED_HOLDOUT_INTERNAL_EVALUATION",
        "scenario_count": 128, "scenario_ids": list(HOLDOUT_IDS),
        "conditions": list(CONDITION_NAMES), "cycles_per_arm": 2,
        "metrics": observed, "mechanism_gate_passed": gate,
        "integrity_coverage": 1.0, "files": checksums,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "interpretation_boundary": "Only synthetic software mechanism. Independent scientific review pending; no phenomenal consciousness inference.",
    }
    _write_json(folder / "manifest.json", manifest)
    audit_holdout(folder)
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--holdout-output", type=Path)
    modes.add_argument("--audit", type=Path)
    modes.add_argument("--verify-release", action="store_true")
    args = parser.parse_args()
    if args.verify_release:
        release = verify_release()
        print(json.dumps({"release_verified": True, "freeze_commit": release["freeze_commit"]}, sort_keys=True))
        return
    result = run_holdout(args.holdout_output) if args.holdout_output else audit_holdout(args.audit)
    print(json.dumps({
        "status": result["status"], "scenario_count": result["scenario_count"],
        "mechanism_gate_passed": result["mechanism_gate_passed"],
        "metrics": result["metrics"],
    }, sort_keys=True))


if __name__ == "__main__":
    main()
