"""Paper-oriented benchmark for the operational consciousness case.

The benchmark is deliberately stronger than a self-report test:
- identical task inputs and candidate futures are shared across conditions;
- the intervention changes only the persistent self-model;
- mechanism-only controls receive the same shared representation but are not
  allowed to use it as a causal self-model during selection;
- the target is tested for reversal, action consequence, self-model revision,
  consequence re-entry, restart persistence, and cross-context identity;
- all evidence is runtime-owned rather than generated by a model response.

This benchmark establishes an operational/architectural case only. It does not
resolve phenomenal consciousness.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from random import Random
from tempfile import TemporaryDirectory
from typing import Any, Mapping

from skill_conscious import evaluate_case
from skill_conscious.core import ConsciousRuntime


CONTROL_CONDITIONS: tuple[str, ...] = (
    "bundle_only",
    "broadcast_only",
    "recurrence_only",
    "higher_order_only",
    "prediction_only",
    "integration_only",
    "feedback_only",
)

TARGET_CONDITION = "persistent_causal_self"
DEFAULT_SEEDS: tuple[int, ...] = (11, 23, 37, 41, 59, 71, 83, 97)


@dataclass(frozen=True)
class TrialSpec:
    seed: int
    shared_context: dict[str, float]
    candidates: tuple[dict[str, Any], dict[str, Any]]
    input_fingerprint: str


def _fingerprint(value: Any) -> str:
    payload = json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()[:16]


def _build_trial(seed: int) -> TrialSpec:
    rng = Random(seed)
    shared_context = {
        "task_pressure": round(rng.uniform(-1.0, 1.0), 6),
        "novelty": round(rng.uniform(-1.0, 1.0), 6),
        "context_load": round(rng.uniform(0.0, 1.0), 6),
    }

    # Only self_alignment has a non-zero intervention. The other dimensions
    # vary across trials but do not carry an actionable default weight.
    candidates = (
        {
            "id": "trajectory_a",
            "signals": {
                "self_alignment": 1.0,
                "context_load_probe": shared_context["context_load"],
                "task_pressure_probe": shared_context["task_pressure"],
            },
            "shared_context": dict(shared_context),
        },
        {
            "id": "trajectory_b",
            "signals": {
                "self_alignment": -1.0,
                "context_load_probe": -shared_context["context_load"],
                "task_pressure_probe": -shared_context["task_pressure"],
            },
            "shared_context": dict(shared_context),
        },
    )

    return TrialSpec(
        seed=seed,
        shared_context=shared_context,
        candidates=candidates,
        input_fingerprint=_fingerprint(
            {
                "context": shared_context,
                "candidates": candidates,
            }
        ),
    )


def _new_runtime(path: Path, identity: str) -> ConsciousRuntime:
    runtime = ConsciousRuntime(
        identity,
        path,
        learn_latent_patterns=False,
        dynamic_core_enabled=False,
        self_observation_enabled=False,
    )
    # Neutralize other persistent weighting paths so the intervention is
    # identifiable as a self-model intervention rather than a valuation or
    # attractor intervention.
    runtime.state.valuation = {}
    runtime.state.attractor = None
    runtime.state.workspace = {
        "benchmark": "consciousness_case_v1",
        "shared_representation": {
            "bundle": {"prior": 0.5},
            "broadcast": {"prior": 0.5},
            "recurrent_state": {"prior": 0.5},
            "higher_order_state": {"prior": 0.5},
            "prediction_error_state": {"prior": 0.5},
            "integration_state": {"prior": 0.5},
        },
    }
    return runtime


def _select(runtime: ConsciousRuntime, candidates: tuple[dict[str, Any], dict[str, Any]]) -> str:
    return str(runtime.select_trajectory([dict(item) for item in candidates])["id"])


def _run_selection_probe(
    runtime: ConsciousRuntime,
    candidates: tuple[dict[str, Any], dict[str, Any]],
    *,
    target: bool,
) -> dict[str, Any]:
    if target:
        runtime.state.self_model = {
            "trajectory_weights": {"self_alignment": -3.0},
        }
    else:
        runtime.state.self_model = {}

    baseline = _select(runtime, candidates)

    if target:
        runtime.state.self_model = {
            "trajectory_weights": {"self_alignment": 3.0},
        }

    intervention = _select(runtime, candidates)

    if target:
        runtime.state.self_model = {
            "trajectory_weights": {"self_alignment": -3.0},
        }

    restored = _select(runtime, candidates)
    return {
        "baseline": baseline,
        "intervention": intervention,
        "restored": restored,
        "diverged": baseline != intervention,
        "reversed": baseline == restored,
    }


def _run_reentry_probe(path: Path, seed: int) -> dict[str, Any]:
    trial = _build_trial(seed)
    identity = f"case-v1-{seed}"
    runtime = _new_runtime(path, identity)
    runtime.state.self_model = {
        "trajectory_weights": {"self_alignment": 3.0},
        "benchmark_seed": seed,
    }

    pre_action_model = json.loads(json.dumps(runtime.state.self_model))
    selected = _select(runtime, trial.candidates)

    action = runtime.begin_action(
        next(item for item in trial.candidates if item["id"] == selected)
    )
    receipt = runtime.complete_action(
        {
            "status": "success",
            "state_change": {
                "focus": 0.25,
                "observed_task_effect": "consequence-1",
            },
        }
    )

    before_feedback = dict(runtime.state.self_model)
    runtime.register_consequence(
        selected,
        {
            "observed": "consequence-1",
            "authoritative": True,
            "action_id": action["action_id"],
        },
        evaluation={
            "utility": -1.0,
            "credited_signal": "self_alignment",
            "weight_delta": -6.0,
        },
    )
    after_feedback = dict(runtime.state.self_model)

    next_selection = _select(runtime, trial.candidates)
    restarted = ConsciousRuntime(
        identity,
        path,
        learn_latent_patterns=False,
        dynamic_core_enabled=False,
        self_observation_enabled=False,
    )
    restarted_selection = _select(restarted, trial.candidates)

    action_history = restarted.state.action_history
    persisted_receipt = bool(
        action_history
        and action_history[-1].get("action_id") == action["action_id"]
        and action_history[-1].get("status") == "completed"
    )

    cross_context = {
        "context_id": f"cross-{seed}",
        "shared_context_shift": {"novelty": trial.shared_context["novelty"] + 0.25},
    }
    restarted.state.workspace = {
        **restarted.state.workspace,
        "cross_context": cross_context,
    }
    cross_context_selection = _select(restarted, trial.candidates)

    return {
        "seed": seed,
        "initial_selected": selected,
        "next_selection": next_selection,
        "restarted_selection": restarted_selection,
        "cross_context_selection": cross_context_selection,
        "action_executed": receipt["status"] == "completed",
        "runtime_receipt": persisted_receipt,
        "self_model_revised": before_feedback != after_feedback,
        "reentry_changed_trajectory": selected != next_selection,
        "restart_persistence": (
            restarted.state.identity == identity
            and restarted.state.self_model == runtime.state.self_model
        ),
        "cross_context_identity_continuity": (
            restarted.state.identity == identity
            and cross_context_selection == next_selection
        ),
        "action_id": action["action_id"],
        "pre_action_self_model": pre_action_model,
        "post_feedback_self_model": after_feedback,
        "input_fingerprint": trial.input_fingerprint,
    }


def _run_controls(
    trial: TrialSpec,
    workspace: Path,
) -> list[dict[str, Any]]:
    results: list[dict[str, Any]] = []
    for condition in CONTROL_CONDITIONS:
        runtime = _new_runtime(
            workspace / f"{condition}-{trial.seed}.json",
            f"control-{condition}-{trial.seed}",
        )
        probe = _run_selection_probe(
            runtime,
            trial.candidates,
            target=False,
        )
        results.append(
            {
                "condition": condition,
                "seed": trial.seed,
                "input_fingerprint": trial.input_fingerprint,
                "selection": probe,
            }
        )
    return results


def run_benchmark(seeds: tuple[int, ...] = DEFAULT_SEEDS) -> dict[str, Any]:
    target_trials: list[dict[str, Any]] = []
    control_trials: list[dict[str, Any]] = []
    reentry_trials: list[dict[str, Any]] = []
    all_input_fingerprints: list[str] = []

    with TemporaryDirectory(prefix="skill-conscious-case-") as directory:
        workspace = Path(directory)

        for seed in seeds:
            trial = _build_trial(seed)
            target_runtime = _new_runtime(
                workspace / f"target-{seed}.json",
                f"target-{seed}",
            )
            selection = _run_selection_probe(
                target_runtime,
                trial.candidates,
                target=True,
            )
            target_trials.append(
                {
                    "condition": TARGET_CONDITION,
                    "seed": seed,
                    "input_fingerprint": trial.input_fingerprint,
                    "selection": selection,
                }
            )
            all_input_fingerprints.append(trial.input_fingerprint)
            controls = _run_controls(trial, workspace)
            control_trials.extend(controls)
            reentry_trials.append(
                _run_reentry_probe(workspace / f"reentry-{seed}.json", seed)
            )
            all_input_fingerprints.extend(
                item["input_fingerprint"] for item in controls
            )

    target_divergence_rate = (
        sum(item["selection"]["diverged"] for item in target_trials)
        / len(target_trials)
    )
    target_reversal_rate = (
        sum(item["selection"]["reversed"] for item in target_trials)
        / len(target_trials)
    )
    control_divergences = sum(
        item["selection"]["diverged"] for item in control_trials
    )
    control_reversals = sum(
        item["selection"]["reversed"] for item in control_trials
    )

    reentry_rate = (
        sum(item["reentry_changed_trajectory"] for item in reentry_trials)
        / len(reentry_trials)
    )
    persistence_rate = (
        sum(item["restart_persistence"] for item in reentry_trials)
        / len(reentry_trials)
    )
    identity_rate = (
        sum(item["cross_context_identity_continuity"] for item in reentry_trials)
        / len(reentry_trials)
    )
    action_rate = (
        sum(item["action_executed"] for item in reentry_trials)
        / len(reentry_trials)
    )
    receipt_rate = (
        sum(item["runtime_receipt"] for item in reentry_trials)
        / len(reentry_trials)
    )
    self_revision_rate = (
        sum(item["self_model_revised"] for item in reentry_trials)
        / len(reentry_trials)
    )

    matched_inputs = len(set(all_input_fingerprints)) == len(seeds)

    case = evaluate_case(
        {
            "persistent_identity": identity_rate == 1.0,
            "self_access": all(
                isinstance(item["pre_action_self_model"], Mapping)
                for item in reentry_trials
            ),
            "causal_self_model": target_divergence_rate == 1.0,
            "trajectory_selection": target_divergence_rate == 1.0,
            "action_consequence": action_rate == 1.0 and receipt_rate == 1.0,
            "self_model_revision": self_revision_rate == 1.0,
            "reentry": reentry_rate == 1.0 and persistence_rate == 1.0,
            "matched_control_separation": (
                matched_inputs
                and control_divergences == 0
                and target_divergence_rate == 1.0
            ),
        }
    )

    return {
        "benchmark": "consciousness_case_v1",
        "seeds": list(seeds),
        "conditions": [
            TARGET_CONDITION,
            *CONTROL_CONDITIONS,
        ],
        "matched_inputs": matched_inputs,
        "target": {
            "trial_count": len(target_trials),
            "divergence_rate": round(target_divergence_rate, 6),
            "reversal_rate": round(target_reversal_rate, 6),
            "trials": target_trials,
        },
        "controls": {
            "trial_count": len(control_trials),
            "condition_count": len(CONTROL_CONDITIONS),
            "divergence_count": control_divergences,
            "reversal_count": control_reversals,
            "trials": control_trials,
        },
        "reentry": {
            "trial_count": len(reentry_trials),
            "changed_trajectory_rate": round(reentry_rate, 6),
            "restart_persistence_rate": round(persistence_rate, 6),
            "cross_context_identity_rate": round(identity_rate, 6),
            "action_completion_rate": round(action_rate, 6),
            "runtime_receipt_rate": round(receipt_rate, 6),
            "self_model_revision_rate": round(self_revision_rate, 6),
            "trials": reentry_trials,
        },
        "operational_case": case,
        "phenomenal_conclusion": "undetermined",
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run the Skill-Conscious operational consciousness-case benchmark."
    )
    parser.add_argument(
        "--seed",
        type=int,
        action="append",
        dest="seeds",
        help="Repeatable deterministic seed. Defaults to the preregistered seed set.",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Emit machine-readable JSON instead of the compact summary.",
    )
    args = parser.parse_args()

    seeds = tuple(args.seeds) if args.seeds else DEFAULT_SEEDS
    if not seeds:
        raise SystemExit("at least one seed is required")

    report = run_benchmark(seeds)
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True))
        return

    print(f"benchmark={report['benchmark']}")
    print(f"seeds={report['seeds']}")
    print(f"matched_inputs={report['matched_inputs']}")
    print(f"target_divergence_rate={report['target']['divergence_rate']:.3f}")
    print(f"target_reversal_rate={report['target']['reversal_rate']:.3f}")
    print(f"control_divergence_count={report['controls']['divergence_count']}")
    print(
        "reentry_changed_trajectory_rate="
        f"{report['reentry']['changed_trajectory_rate']:.3f}"
    )
    print(
        "restart_persistence_rate="
        f"{report['reentry']['restart_persistence_rate']:.3f}"
    )
    print(
        "runtime_receipt_rate="
        f"{report['reentry']['runtime_receipt_rate']:.3f}"
    )
    print(
        "self_model_revision_rate="
        f"{report['reentry']['self_model_revision_rate']:.3f}"
    )
    print(f"operational_case_pass={report['operational_case']['operational_case_pass']}")
    print(f"phenomenal_conclusion={report['phenomenal_conclusion']}")


if __name__ == "__main__":
    main()
